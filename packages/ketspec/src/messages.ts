export const SPEC_LOCALES = ['en', 'vi'] as const
export type SpecLocale = (typeof SPEC_LOCALES)[number]

export const SPEC_MESSAGES: Record<SpecLocale, Record<MessageKey, string>> = { en, vi }

export type Translate = ((key: MessageKey, params?: Record<string, string | number>) => string) & {
  locale: SpecLocale
}

/** Unknown locales fall back to English; `vi-VN` resolves to `vi`. */
export const specLocale = (value: string | null | undefined): SpecLocale => {
  const base = (value ?? '').toLowerCase().split(/[-_]/)[0]
  return (SPEC_LOCALES as readonly string[]).includes(base ?? '') ? (base as SpecLocale) : 'en'
}

export const specTranslator = (locale: string | null | undefined): Translate => {
  const resolved = specLocale(locale)
  const catalog = SPEC_MESSAGES[resolved]
  const format = new Intl.NumberFormat(resolved)
  const translate = (key: MessageKey, params: Record<string, string | number> = {}) =>
    catalog[key].replace(/\{(\w+)\}/g, (whole, name: string) => {
      const value = params[name]
      if (value === undefined) return whole
      return typeof value === 'number' ? format.format(value) : value
    })
  return Object.assign(translate, { locale: resolved })
}
