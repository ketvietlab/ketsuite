// Bundles the Flow collaborative editor's client-side TypeScript (which
// imports yjs, a real npm dependency) into one self-contained ESM file the
// framework can serve verbatim. This remains separate from the backend island
// builder because Flow also bundles the yjs dependency, while the backend
// islands only compile typed TSX and keep the shared view runtime external.
//
// The output lands next to the kit's other client assets, which is where
// flow_backend points its `assets` URL — the same arrangement mail_backend
// uses for the chatter.

import { existsSync, cpSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'
import { buildFlowHelp } from './build-flow-help.mjs'

/**
 * The view runtime is served by the framework at a fixed URL, so it is
 * resolved to that URL rather than bundled — the same plugin
 * tools/build-backend-client.mjs uses, and for a reason worth stating: a
 * bundled second copy is not merely bigger, it is a *different* runtime. Its
 * `TemplateResult`s fail the page runtime's `isResult()` check, so an island's
 * whole child list stringified to `[object Object]` and hydration died on
 * "expected a text node". This file used to say `external: ['/_ket/view/index.js']`,
 * which was right while the entry was hand-written `.mjs` importing that URL
 * literally; once it became `.tsx` importing `@ketvietlab/ketjs-view`, the
 * pattern matched nothing and the runtime came along silently.
 */
/** @type {import('esbuild').Plugin} */
const ketViewRuntime = {
  name: 'ket-view-runtime',
  setup(build) {
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view$/ }, () => ({
      path: '/_ket/view/index.js',
      external: true,
    }))
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view\/jsx-runtime$/ }, () => ({
      path: '/_ket/view/jsx-runtime.js',
      external: true,
    }))
  },
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const UI_DIR = join(ROOT, 'packages/ketsuite/src/ui/client')
const ENTRY = join(UI_DIR, 'live-doc-view.tsx')
const OUTFILE = join(UI_DIR, 'live-doc.mjs')

export async function buildFlowClient() {
  buildFlowHelp()
  if (!existsSync(ENTRY)) return false
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    // External rather than linked: a minified bundle's map inlines the
    // whole original source, so it is not something the asset mount will
    // serve (packages/ketjs/src/server/http.ts). Writing it without the
    // `sourceMappingURL` comment keeps it on disk for anyone debugging
    // locally without pointing every browser at a URL that must 404.
    sourcemap: 'external',
    // Every .mjs under the kit's client directory carries this, and the
    // generated one is no different: tsconfig.build.json type-checks that
    // directory, and a minified yjs bundle is not code TypeScript can have an
    // opinion about.
    banner: { js: '// @ts-nocheck Generated by tools/build-flow-client.mjs — do not edit.' },
    logLevel: 'warning',
    plugins: [ketViewRuntime],
  })
  const vendor = join(ROOT, 'packages/flow-client/client/vendor')
  mkdirSync(vendor, { recursive: true })
  // Native delivery and Atlas use the same public editor; only transport differs.
  cpSync(OUTFILE, join(vendor, 'live-doc.mjs'))
  const ket = dirname(fileURLToPath(import.meta.resolve('@ketvietlab/ketjs')))
  await esbuild.build({
    entryPoints: [join(ket, 'kernel/i18n.js')],
    outfile: join(vendor, 'ketjs-i18n.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    logLevel: 'warning',
  })
  for (const [specifier, filename] of [
    ['index.tsx', 'date-picker.mjs'],
    ['runtime.js', 'date-picker-runtime.mjs'],
  ]) {
    await esbuild.build({
      entryPoints: [join(ROOT, 'packages/design-system/src/forms/date-time', specifier)],
      outfile: join(vendor, filename),
      bundle: true,
      format: 'esm',
      platform: 'browser',
      target: 'es2022',
      minify: true,
      plugins: [ketViewRuntime],
      logLevel: 'warning',
    })
  }
  // One canonical browser build for native delivery and Atlas. Keep the shared
  // view runtime, locale registries and extension registry as singletons.
  const client = join(ROOT, 'packages/flow-client/client')
  await esbuild.build({
    stdin: {
      contents:
        "export { createFlowWorkspace } from './workspace.mjs'; export { createProductionWorkspace } from './production-entry.mjs'; export * from '@ketvietlab/flow-ui'; export * from '@ketvietlab/flow-ui/workspace'; export * from '@ketvietlab/flow-ui/runtime';",
      resolveDir: client,
      sourcefile: 'workspace-browser-entry.mjs',
    },
    outfile: join(client, 'workspace.browser.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minifyIdentifiers: true,
    minifyWhitespace: true,
    minifySyntax: true,
    legalComments: 'linked',
    sourcemap: 'external',
    logLevel: 'warning',
    external: ['@ketvietlab/ketjs'],
    banner: { js: '// @ts-nocheck Generated from the canonical Flow client; do not edit.' },
    plugins: [
      ketViewRuntime,
      {
        name: 'flow-shared-browser-boundaries',
        setup(build) {
          build.onResolve({ filter: /^@ketvietlab\/design-system\/help\/runtime$/ }, () => ({
            path: join(ROOT, 'packages/design-system/src/runtime/help.js'),
          }))
          build.onResolve({ filter: /^@ketvietlab\/flow-client(?:\/.*)?$/ }, (args) => {
            let name = args.path.split('/').slice(2).join('/') || 'workspace.mjs'
            if (!name.endsWith('.mjs')) name += '.mjs'
            if (
              [
                'i18n.mjs',
                'extensions.mjs',
                'routes.mjs',
                'navigation.mjs',
                'navigation-host.mjs',
                'help.generated.mjs',
                'organization.mjs',
                'operations.mjs',
              ].includes(name)
            )
              return { path: '@ketvietlab/flow-client/' + name, external: true }
            return { path: join(client, name) }
          })
          build.onResolve(
            { filter: /^@ketvietlab\/flow-ui(?:\/(workspace|documents|runtime))?$/ },
            (args) => ({
              path: join(ROOT, 'packages/flow-ui/src', (args.path.split('/')[2] ?? 'index') + '.mjs'),
            }),
          )
          build.onResolve({ filter: /(?:^|\/)i18n(?:\.mjs)?$/ }, (args) => {
            if (args.path === '@ketvietlab/flow-ui/i18n' || args.importer.includes('/flow-ui/'))
              return { path: '@ketvietlab/flow-ui/i18n', external: true }
            if (args.importer.startsWith(client))
              return { path: '@ketvietlab/flow-client/i18n.mjs', external: true }
          })
          build.onResolve(
            {
              filter:
                /(?:^|\/)(extensions|routes|navigation|navigation-host|help\.generated|organization|operations)\.mjs$/,
            },
            (args) =>
              args.importer.startsWith(client)
                ? { path: '@ketvietlab/flow-client/' + args.path.split('/').at(-1), external: true }
                : undefined,
          )
        },
      },
    ],
  })
  return true
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const built = await buildFlowClient()
  console.log(
    built ? `bundled flow_backend client into ${OUTFILE}` : 'flow_backend has no client entry yet, skipped',
  )
}
