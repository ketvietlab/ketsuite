// Bundles Mermaid for the backend's screen help, the way tools/build-design-system-mermaid.mjs does
// for the catalogue: the DS runtime draws ```mermaid fences in a HelpDrawer only once the host
// configures a loader (`configureMermaidLoader`), and the DS itself depends on no renderer.
//
// The output lands in the backend module's assets directory beside the other generated clients,
// so the shell client loads it from its own URL. Splitting keeps each diagram type in its own
// chunk; nothing is fetched until a guide with a diagram is opened.

import { rm } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
// The catalogue's adapter: one pinned Mermaid for every host, and none inside the published package.
const ENTRY = join(ROOT, 'apps/design-system/mermaid-vendor.ts')
export const BACKEND_MERMAID_DIR = join(ROOT, 'packages/ketsuite/src/modules/backend/design/client/mermaid')

export async function buildBackendMermaid() {
  // Chunk names carry content hashes; a rebuild must not leave the previous set beside the new one.
  await rm(BACKEND_MERMAID_DIR, { recursive: true, force: true })
  await build({
    entryPoints: { mermaid: ENTRY },
    outdir: BACKEND_MERMAID_DIR,
    bundle: true,
    splitting: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    outExtension: { '.js': '.mjs' },
    minify: true,
    banner: { js: '// @ts-nocheck Generated by tools/build-backend-mermaid.mjs — do not edit.' },
    logLevel: 'warning',
  })
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildBackendMermaid()
  console.log(`bundled Mermaid for screen help into ${BACKEND_MERMAID_DIR}`)
}
