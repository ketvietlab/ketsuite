// Bundles Spec's browser entry into one self-contained ESM file.
//
// Unlike the suite's islands, a Spec page is not served by the framework: the
// `ketspec` command writes a static site that any file server can host. There
// is no `/_ket/view/` URL to resolve the view runtime against, so the bundle
// carries its own copy of @ketvietlab/ketjs-view, the design-system components
// it renders and the design-system runtime — the same reason
// tools/build-design-system-atlas-runtime.mjs gives for a KetAtlas mock.
//
// Workspace packages resolve through tsconfig.base.json's paths to their
// sources, because this runs before the TypeScript build produces any dist.

import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'packages/ketspec/src/browser.ts')
const OUTFILE = join(ROOT, 'packages/ketspec/src/browser/ketspec.mjs')

export async function buildKetspecClient() {
  if (!existsSync(ENTRY)) return false
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    // Published inside the package and copied into every generated site, so no
    // source map: it would inline the whole original source next to each page.
    sourcemap: false,
    tsconfig: join(ROOT, 'tsconfig.base.json'),
    // tsconfig.build.json type-checks every file under packages/*/src; a
    // minified bundle is not code TypeScript can have an opinion about.
    banner: { js: '// @ts-nocheck Generated by tools/build-ketspec-client.mjs — do not edit.' },
    logLevel: 'warning',
  })
  return true
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const built = await buildKetspecClient()
  console.log(
    built ? `bundled the Spec browser entry into ${OUTFILE}` : 'Spec has no browser entry yet, skipped',
  )
}
